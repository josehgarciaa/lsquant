"""Check copied shell commands without starting any documented program.

The checks read Markdown, tokenize shell fragments, and use the real CLI
parser and run-file inspection routine. Each scan is linear in the page
text and referenced JSON sizes; no numerical calculation is requested.

Warnings
--------
Pitfall: shell examples mix repository inputs, generated data, and paths
supplied by the reader. Exceptions below describe the latter explicitly.
This is a shell subset, not an interpreter; substitutions are never run.
"""

