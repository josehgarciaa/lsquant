@dataclass(frozen=True)
class _Block:
    page: Path
    line: int
    text: str

    @property
    def label(self):
        return f"{self.page.relative_to(REPO)}:{self.line}"


def _blocks(page):
    """Extract shell fences, retaining physical line numbers for diagnostics."""
    fence = None
    start = 0
    body = []
    for number, line in enumerate(page.read_text().splitlines(), 1):
        match = re.match(r"^\s*(`{3,}|~{3,})\s*(\w*)[^\n]*$", line)
        if fence is None:
            if match:
                fence = match[1]
                start = number
                language = match[2].lower()
                body = []
        elif re.match(rf"^\s*{re.escape(fence[0])}{{{len(fence)},}}\s*$", line):
            if language in {"bash", "sh", "console"}:
                yield _Block(page, start, "\n".join(body))
            fence = None
        else:
            body.append(line)


BLOCKS = [block for page in PAGES for block in _blocks(page)]


def _commands(block):
    """Join continuations and omit here-document bodies without executing them.

    Quoted inline Python remains one token. Shell punctuation separates
    commands, while angle-bracket placeholders remain intact.
    """
    pending = ""
    delimiter = None
    for offset, physical in enumerate(block.text.splitlines(), 1):
        line = re.sub(r"^\s*\$ ", "", physical).strip()
        if delimiter:
            if line == delimiter:
                delimiter = None
            continue
        if not pending:
            first = block.line + offset
        pending += line[:-1] + " " if line.endswith("\\") else line
        if line.endswith("\\"):
            continue
        here = re.search(r"<<-?\s*['\"]?(\w+)", pending)
        if here:
            delimiter = here[1]
            pending = pending[:here.start()]
        # Parentheses around a subshell do not change its argument paths.
        fragment = pending.strip()
        if fragment.startswith("(") and fragment.endswith(")"):
            fragment = fragment[1:-1]
        lexer = shlex.shlex(fragment, posix=True, punctuation_chars=";&|")
        lexer.whitespace_split = True
        tokens = []
        for token in lexer:
            if token in {";", "&&", "||", "|", "&"}:
                if tokens:
                    yield first, tokens
                tokens = []
            else:
                tokens.append(token)
        if tokens:
            yield first, tokens
        pending = ""


def _python_args(tokens):
    for index in range(len(tokens) - 3):
        if (tokens[index] in {"python", "python3"}
                and tokens[index + 1:index + 3] == ["-m", "lsquant"]):
            return tokens[index + 3:]
    return None


@pytest.fixture(scope="module")
def api():
    """Load the real schema without invoking any CLI execution branch."""
    from lsquant.cli import _build_parser
    from lsquant.runfile import inspect_target
    return _build_parser(), inspect_target


@pytest.mark.parametrize("block", BLOCKS, ids=lambda block: block.label)
def test_python_cli_arguments(block, api):
    """Reject obsolete verbs and options using the maintained argument parser."""
    parser, _ = api
    for line, tokens in _commands(block):
        args = _python_args(tokens)
        if args is not None:
            # Redirections belong to the shell rather than the CLI.
            stop = next((i for i, token in enumerate(args)
                         if token in {">", ">>", "<", "2>&1"}), len(args))
            try:
                parser.parse_args(args[:stop])
            except SystemExit as exc:
                pytest.fail(f"{block.page.relative_to(REPO)}:{line}: "
                            f"CLI rejected {args[:stop]!r} (exit {exc.code})")


def _reader_input(token):
    return any(token == prefix or (prefix.endswith(("/", "_"))
                                  and token.startswith(prefix))
               for prefix in READER_INPUTS)


def _path_argument(token):
    if token.startswith("-") or "://" in token:
        return False
    return ("/" in token or bool(re.search(
        r"\.(py|sh|json|npz|npy|dat|in|fdf|win|spn|eig|xyz|scfout|gpw|pth|CSR|chebmom\w*)$",
        token)) or token == "SHA256SUMS")


def _output(path, outputs):
    return ("out" in path.parts or "build" in path.parts
            or path == Path("/tmp") or Path("/tmp") in path.parents
            or any(path == out or out in path.parents for out in outputs)
            or (".chebmom" in path.name
                and path.parent / ".generated_moments" in outputs))


def _inputs(page):
    """Resolve inputs in page order, carrying outputs and shell variables.

    Bare scripts on example pages imply that example's directory. Explicit
    repository paths imply the root. DFT preparation commands use the local
    input subdirectory named by their existing input file. No path is
    created and no shell environment is modified.
    """
    cwd = REPO
    outputs = set()
    variables = {"PWD": str(REPO)}
    for block in _blocks(page):
        local = cwd
        for line, tokens in _commands(block):
            tokens = [re.sub(r"\$(\w+)|\$\{(\w+)\}",
                             lambda m: variables.get(m[1] or m[2], m[0]), t)
                      for t in tokens]
            while tokens and re.match(r"^\w+=", tokens[0]):
                name, value = tokens.pop(0).split("=", 1)
                variables[name] = value
            if not tokens:
                continue
            if tokens[0] == "cd":
                target = tokens[1]
                if target == "lsquant" or "$" in target or "lsquant" == Path(target).name:
                    local = REPO
                elif not _reader_input(target):
                    local = (local / target).resolve()
                    yield block, line, local, False
                continue
            base = local
            if page.parent.parent.name == "examples" and local == REPO:
                bare = [t for t in tokens if _path_argument(t) and "/" not in t]
                if bare:
                    base = page.parent
                    for subdir in ("qe", "paoflow", "siesta", "openmx"):
                        if any((base / subdir / t).exists() for t in bare):
                            base = base / subdir
                            break
                if any(t.startswith("../w90") for t in tokens):
                    base = page.parent / "qe"
            next_outputs = set()
            for index, token in enumerate(tokens):
                previous = tokens[index - 1] if index else ""
                if tokens[0] == "mkdir" and not token.startswith("-") and index:
                    next_outputs.add((base / token).resolve())
                    continue
                if previous in {"--out", "-o", "--out-dir", ">", ">>"}:
                    next_outputs.add((base / token).resolve())
                    continue
                if token.startswith(("--out=", "--out-dir=")):
                    next_outputs.add((base / token.split("=", 1)[1]).resolve())
                    continue
                if (not _path_argument(token) or _reader_input(token)
                        or "$" in token or "=" in token or " " in token):
                    continue
                path = (REPO / token if token.startswith(
                    ("examples/", "scripts/", "python/", "goldens/"))
                    else base / token).resolve()
                if not _output(path, outputs):
                    args = _python_args(tokens)
                    is_run = bool(args and args[0] in {"run", "inspect"}
                                  and len(args) > 1 and token == args[1]
                                  and path.suffix == ".json")
                    yield block, line, path, is_run
            outputs.update(next_outputs)
            if (Path(tokens[0]).name == "lsquant" and len(tokens) > 1
                    and tokens[1] == "compute"):
                outputs.add(base / ".generated_moments")
            for token in tokens:
                for directory in GENERATOR_OUTPUTS.get(Path(token).name, ()):
                    outputs.add((base / directory).resolve())
            # A run file supplies its own default destination without running it.
            args = _python_args(tokens)
            if args and args[0] == "run" and len(args) > 1:
                import json
                path = REPO / args[1]
                if path.is_file():
                    destination = json.loads(path.read_text()).get("output", {}).get("dir")
                    if destination:
                        outputs.add((REPO / destination).resolve())
        # A parenthesized cd is scoped to its block; ordinary cd persists.
        if not block.text.lstrip().startswith("("):
            cwd = local


@pytest.mark.parametrize("block", BLOCKS, ids=lambda block: block.label)
def test_repository_inputs(block):
    """Require repository inputs while allowing classified earlier outputs."""
    for owner, line, path, _ in _inputs(block.page):
        if owner == block:
            assert path.exists() or ("*" in str(path) and any(
                path.parent.glob(path.name))), f"{block.label}:{line}: missing input {path}"


@pytest.mark.parametrize("block", BLOCKS, ids=lambda block: block.label)
def test_documented_runfiles(block, api):
    """Apply precisely the JSON inspection validation, with no model execution."""
    _, inspect = api
    for owner, line, path, is_run in _inputs(block.page):
        if owner == block and is_run and path.is_file():
            try:
                inspect(str(path))
            except Exception as exc:
                pytest.fail(f"{block.label}:{line}: {path.name}: {exc}")


LEGACY = [block for block in BLOCKS if any(
    Path(tokens[0]).name == "lsquant" and len(tokens) > 1
    and tokens[1] in {"compute", "reconstruct"}
    for _, tokens in _commands(block))]


@pytest.mark.parametrize("block", LEGACY, ids=lambda block: block.label)
def test_legacy_binary_is_identified(block):
    """Require a nearby explanation of the two distinct command interfaces."""
    lines = block.page.read_text().splitlines()
    nearby = " ".join(lines[max(0, block.line - 13):block.line + 2]).lower()
    assert all(term in nearby for term in (
        "compiled", "build/", "lsquant", "not", "python -m lsquant")), block.label


def test_shell_subset_preserves_commands_and_lines(tmp_path):
    """Protect prompt, continuation, directory, and here-document handling."""
    page = tmp_path / "README.md"
    page.write_text(
        "~~~console\n"
        "$ cd examples/demo && python3 -m lsquant run \\\n"
        "  recipe.json --out /tmp/demo\n"
        "cat > generated.json <<'JSON'\n"
        '{"not": "a command"}\n'
        "JSON\n"
        "$ python -m lsquant inspect /tmp/demo\n"
        "~~~\n"
        "```python\nignored()\n```\n"
    )
    blocks = list(_blocks(page))
    assert len(blocks) == 1
    assert list(_commands(blocks[0])) == [
        (2, ["cd", "examples/demo"]),
        (2, ["python3", "-m", "lsquant", "run", "recipe.json",
             "--out", "/tmp/demo"]),
        (4, ["cat", ">", "generated.json"]),
        (7, ["python", "-m", "lsquant", "inspect", "/tmp/demo"]),
    ]
